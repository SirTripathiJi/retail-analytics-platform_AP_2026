-- Q33. Allocate a payment to a matching customer's outstanding credit invoice
-- WRITE
-- The statement inserts only when payment and invoice belong to the same
-- customer, the invoice is eligible, and neither amount is over-allocated.
-- Run in a transaction and lock/check the payment and invoice rows in a real
-- implementation to protect against concurrent allocation requests.
INSERT INTO payment_allocations
    (payment_id, invoice_id, allocated_amount_paise)
SELECT
    p.payment_id,
    i.invoice_id,
    :allocated_amount_paise
FROM payments AS p
JOIN invoices AS i
    ON i.invoice_id = :invoice_id
   AND i.customer_id = p.customer_id
WHERE p.payment_id = :payment_id
  AND p.customer_id IS NOT NULL
  AND i.invoice_type = 'credit'
  AND i.status IN ('unpaid', 'partially_paid')
  AND :allocated_amount_paise > 0
  AND :allocated_amount_paise <= (i.total_paise - i.amount_paid_paise)
  AND :allocated_amount_paise <= (
      p.amount_paise - COALESCE(
          (SELECT SUM(existing.allocated_amount_paise)
           FROM payment_allocations AS existing
           WHERE existing.payment_id = p.payment_id),
          0
      )
  )
  AND NOT EXISTS (
      SELECT 1
      FROM payment_allocations AS existing
      WHERE existing.payment_id = p.payment_id
        AND existing.invoice_id = i.invoice_id
  )
RETURNING *;

-- Q34. Recalculate an invoice's paid amount and status after allocations
-- WRITE
-- Execute in the same transaction as the payment allocation. The target
-- invoice is retained even when it has no allocations (LEFT JOIN => zero).
WITH allocation_totals AS (
    SELECT
        invoice_id,
        SUM(allocated_amount_paise) AS total_paid
    FROM payment_allocations
    WHERE invoice_id = :invoice_id
    GROUP BY invoice_id
)
UPDATE invoices AS i
SET amount_paid_paise = COALESCE(a.total_paid, 0),
    status = CASE
        WHEN i.status = 'cancelled' THEN 'cancelled'
        WHEN COALESCE(a.total_paid, 0) = 0 THEN 'unpaid'
        WHEN COALESCE(a.total_paid, 0) < i.total_paise THEN 'partially_paid'
        ELSE 'paid'
    END
FROM (SELECT invoice_id FROM invoices WHERE invoice_id = :invoice_id) AS target
LEFT JOIN allocation_totals AS a
    ON a.invoice_id = target.invoice_id
WHERE i.invoice_id = target.invoice_id
RETURNING i.*;

