-- Q40. Calculate sales by category for a selected period
-- READ
-- This groups by the product's current category. For historically exact
-- category reporting, store a category-name/ID snapshot on invoice_items.
SELECT
    c.category_id,
    c.name AS category_name,
    SUM(ii.quantity) AS units_sold,
    SUM(ii.line_total_paise) AS sales_paise
FROM invoice_items AS ii
JOIN invoices AS i
    ON i.invoice_id = ii.invoice_id
JOIN products AS p
    ON p.product_id = ii.product_id
JOIN categories AS c
    ON c.category_id = p.category_id
WHERE i.status <> 'cancelled'
  AND i.created_at >= :start_timestamp
  AND i.created_at < :end_timestamp
GROUP BY c.category_id, c.name
ORDER BY sales_paise DESC;

-- Q41. Estimate gross profit using the product's current cost price
-- READ
-- This is an estimate, not historical profit: invoice_items in the supplied
-- reference schema has no sale-time cost-price snapshot column. A production
-- historical-profit report should add and use unit_cost_snapshot_paise.
SELECT
    COALESCE(SUM(ii.line_total_paise), 0) AS sales_paise,
    COALESCE(
        SUM(ii.quantity * COALESCE(p.cost_price_paise, 0)),
        0
    ) AS estimated_cost_paise,
    COALESCE(SUM(ii.line_total_paise), 0)
      - COALESCE(
          SUM(ii.quantity * COALESCE(p.cost_price_paise, 0)),
          0
        ) AS estimated_gross_profit_paise
FROM invoice_items AS ii
JOIN invoices AS i
    ON i.invoice_id = ii.invoice_id
LEFT JOIN products AS p
    ON p.product_id = ii.product_id
WHERE i.status <> 'cancelled'
  AND i.created_at >= :start_timestamp
  AND i.created_at < :end_timestamp;

