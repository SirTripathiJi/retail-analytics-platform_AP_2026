-- Q24. Calculate a customer's outstanding Khata balance
-- READ
-- Sign convention: CREDIT increases dues, PAYMENT decreases dues,
-- and a positive ADJUSTMENT increases dues in this reference model.
SELECT
    c.customer_id,
    c.name AS customer_name,
    COALESCE(
        SUM(
            CASE
                WHEN k.entry_type = 'credit' THEN k.amount_paise
                WHEN k.entry_type = 'payment' THEN -k.amount_paise
                WHEN k.entry_type = 'adjustment' THEN k.amount_paise
                ELSE 0
            END
        ),
        0
    ) AS outstanding_balance_paise
FROM customers AS c
LEFT JOIN khata_entries AS k
    ON k.customer_id = c.customer_id
WHERE c.customer_id = :customer_id
GROUP BY c.customer_id, c.name;

-- Q25. List customers with a positive outstanding balance
-- READ
WITH customer_balances AS (
    SELECT
        k.customer_id,
        SUM(
            CASE
                WHEN k.entry_type = 'credit' THEN k.amount_paise
                WHEN k.entry_type = 'payment' THEN -k.amount_paise
                WHEN k.entry_type = 'adjustment' THEN k.amount_paise
                ELSE 0
            END
        ) AS outstanding_balance_paise
    FROM khata_entries AS k
    GROUP BY k.customer_id
)
SELECT
    c.customer_id,
    c.name,
    c.phone,
    cb.outstanding_balance_paise
FROM customers AS c
JOIN customer_balances AS cb
    ON cb.customer_id = c.customer_id
WHERE cb.outstanding_balance_paise > 0
ORDER BY cb.outstanding_balance_paise DESC, c.name ASC;

