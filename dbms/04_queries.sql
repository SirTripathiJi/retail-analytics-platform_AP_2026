-- Q43. Find least-selling active products, including products with zero sales
-- READ
-- Aggregate only non-cancelled invoice lines first. This prevents quantities
-- from cancelled invoices being counted while retaining zero-sales products.
WITH product_sales AS (
    SELECT
        ii.product_id,
        SUM(ii.quantity) AS units_sold
    FROM invoice_items AS ii
    JOIN invoices AS i
        ON i.invoice_id = ii.invoice_id
    WHERE i.status <> 'cancelled'
      AND ii.product_id IS NOT NULL
    GROUP BY ii.product_id
)
SELECT
    p.product_id,
    p.name,
    COALESCE(ps.units_sold, 0) AS units_sold
FROM products AS p
LEFT JOIN product_sales AS ps
    ON ps.product_id = p.product_id
WHERE p.is_active = TRUE
ORDER BY units_sold ASC, p.name ASC
LIMIT 10;

