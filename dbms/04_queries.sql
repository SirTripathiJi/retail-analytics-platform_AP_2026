-- IMPORTANT:
-- The application uses MongoDB with a BYOD tenant architecture.
-- These are PostgreSQL-compatible reference queries for academic
-- documentation and evaluation. They are NOT executed against MongoDB.
--
-- Run CENTRAL DATABASE queries against the central account database.
-- Run TENANT DATABASE queries against the selected shopkeeper database.
-- Replace :parameter placeholders with values supplied by your SQL client
-- or application. They are illustrative named parameters, not psql syntax.
--
-- QUERY CLASSIFICATION:
-- READ  = retrieves data (SELECT, including SELECT-based reports/CTEs).
-- WRITE = changes data (INSERT, UPDATE, or DELETE).
-- For statements containing subqueries, classify by the outer/main statement.
--
-- JOIN GUIDELINE:
-- JOIN related tables when the result needs columns or validation from more
-- than one relation. Do not add an unnecessary JOIN to a single-table lookup,
-- aggregate, INSERT, UPDATE, or DELETE. UNION ALL is used where independent
-- event sources are combined into one result set.
--
-- FINANCIAL AND TRANSACTION NOTES:
-- Monetary columns use integer paise. Run related multi-table writes (invoice
-- creation, stock changes, payment allocation/status updates, cancellation,
-- and reset) inside a database transaction in a real relational deployment.
-- These queries are reference examples; application-level authorization,
-- tenant scoping, validation, locking, and audit rules must also be enforced.

